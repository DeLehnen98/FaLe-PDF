export function t(lang, key, vars = {}) {
  const v = (S[lang] || S.de)[key] ?? S.de[key] ?? key;
  if (typeof v === 'function') return v(vars);
  return String(v).replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

/** Resolve a tool text: a plain string or {de, en}. */
export function pick(lang, value) {
  if (value == null) return '';
  if (typeof value === 'string') return value;
  return value[lang] ?? value.de ?? value.en ?? '';
}
