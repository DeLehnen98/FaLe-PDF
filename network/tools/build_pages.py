def popular_tools(lang, limit=6):
    """(name, path) of the tools marked "popular" in tools/webtools/specs/*.json (sorted by order, id)."""
    specs = []
    for f in sorted((ROOT / 'tools' / 'webtools' / 'specs').glob('*.json')):
        sp = json.loads(f.read_text(encoding='utf-8'))
        if sp.get('popular'):
            specs.append(sp)
    specs.sort(key=lambda sp: (sp.get('order', 1000), sp['id']))
    hub = TOOLS_HUB[0 if lang == 'de' else 1]
    return [(sp[lang]['name'], f"{hub}{sp[lang]['slug']}/") for sp in specs[:limit]]


