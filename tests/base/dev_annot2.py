import os
from playwright.sync_api import sync_playwright
SP = os.path.dirname(os.path.abspath(__file__))
with sync_playwright() as p:
    b = p.chromium.launch()
    page = b.new_page(viewport={'width': 1366, 'height': 860})
    page.on('console', lambda m: print('LOG', m.text))
    page.on('pageerror', lambda e: print('ERR', e))
    page.goto('http://127.0.0.1:8792/')
    page.set_input_files('#pdf-input', [os.path.join(SP, 'testdata', 'bericht.pdf')])
    page.wait_for_function("location.hash.startsWith('#/ansicht/')")
    page.wait_for_function("document.querySelector('[data-v=loading]').hidden")
    docid = page.evaluate("location.hash.split('/')[2].split('?')[0]")
    page.evaluate(f"location.hash = '#/werkzeug/kommentieren?doc={docid}'")
    page.wait_for_selector('.pt-page canvas')
    bb = page.locator('.pt-page').first.bounding_box()
    s = page.evaluate("parseFloat(getComputedStyle(document.querySelector('.pt-stage')).getPropertyValue('--s'))")
    at = lambda x, y: (bb['x'] + x * s, bb['y'] + y * s)
    page.locator('[data-tool=rect]').click()
    page.evaluate("document.querySelector('.pt-pages').addEventListener('pointerdown', e => console.log('down', e.target.className && e.target.className.baseVal !== undefined ? 'svg:' + e.target.tagName : e.target.className), true)")
    page.mouse.move(*at(80, 450)); page.mouse.down(); page.mouse.move(*at(200, 520), steps=6); page.mouse.up()
    page.wait_for_timeout(300)
    print('svg children', page.evaluate("document.querySelector('.pt-page svg').children.length"), page.locator('.screen-foot .foot-info').inner_text())
    page.locator('[data-tool=text]').click()
    page.mouse.click(*at(100, 620))
    page.wait_for_timeout(300)
    print('active', page.evaluate("document.activeElement.className"))
    page.keyboard.type('Hallo')
    print('text els', page.evaluate("Array.from(document.querySelectorAll('.pt-text')).map(e => e.textContent + '|' + e.className)"))
    b.close()
