import os
from playwright.sync_api import sync_playwright
SP = os.path.dirname(os.path.abspath(__file__))
with sync_playwright() as p:
    b = p.chromium.launch()
    page = b.new_page(viewport={'width': 1366, 'height': 860})
    page.on('pageerror', lambda e: print('ERR', e))
    page.on('console', lambda m: print('LOG', m.text))
    page.goto('http://127.0.0.1:8792/')
    page.set_input_files('#pdf-input', [os.path.join(SP, 'testdata', 'bericht.pdf')])
    page.wait_for_function("location.hash.startsWith('#/ansicht/')")
    page.wait_for_function("document.querySelector('[data-v=loading]').hidden")
    docid = page.evaluate("location.hash.split('/')[2].split('?')[0]")
    page.evaluate(f"location.hash = '#/werkzeug/kommentieren?doc={docid}'")
    page.wait_for_selector('.pt-page canvas')
    bb = page.locator('.pt-page').first.bounding_box()
    s = page.evaluate("parseFloat(getComputedStyle(document.querySelector('.pt-stage')).getPropertyValue('--s'))")
    at = lambda x, y: (bb['x'] + x * s, bb['y'] + y * s)
    page.locator('.pt-tool[data-tool=line]').click()
    page.evaluate("""for (const ev of ['pointerdown','pointermove','pointerup','pointercancel']) document.querySelector('.pt-pages').addEventListener(ev, e => console.log(ev, e.pointerId, e.target.tagName, e.target.getAttribute('class')), true)""")
    x, y = at(360, 320)
    print('elementFromPoint', page.evaluate(f"document.elementFromPoint({x},{y}).outerHTML.slice(0,80)"))
    page.mouse.move(x, y); page.mouse.down(); page.mouse.move(*at(480, 340), steps=3); page.mouse.up()
    page.wait_for_timeout(200)
    print(page.locator('.screen-foot .foot-info').inner_text())
    b.close()
