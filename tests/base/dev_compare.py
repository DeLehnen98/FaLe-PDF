from playwright.sync_api import sync_playwright
from pplus_common import *
ensure_server()
with sync_playwright() as p:
    b = launch(p)
    ctx = context(b); pg = ctx.new_page(); attach(pg, 'desk')
    pg.goto(URL); pg.wait_for_timeout(800)
    import_pdfs(pg, [os.path.join(TDP, 'bericht_v1.pdf'), os.path.join(TDP, 'bericht_v2.pdf')])
    a, bb = doc_id(pg, 'bericht_v1.pdf'), doc_id(pg, 'bericht_v2.pdf')
    goto(pg, f'#/werkzeug/vergleichen?doc={a}', '.cmp-slot')
    pg.locator('[data-slot=b] button').click()
    pg.wait_for_selector('dialog .pick-item')
    pg.locator(f'dialog input[value="{bb}"]').check()
    pg.locator('dialog .btn-primary').click()
    pg.wait_for_timeout(400)
    pg.locator('.screen-foot .btn-primary').click()
    pg.wait_for_selector('.cmp-summary', timeout=20000)
    pg.wait_for_selector('.cmp-side canvas', timeout=20000)
    pg.wait_for_timeout(800)
    print(pg.evaluate("Array.from(document.querySelectorAll('.cmp-stats b')).map(e=>e.textContent)"))
    shot(pg, 'dev_cmp_side')
    pg.locator('[data-view=text]').click(); pg.wait_for_timeout(500)
    print(pg.evaluate("Array.from(document.querySelectorAll('.cmp-change p')).map(e=>e.textContent)"))
    shot(pg, 'dev_cmp_text')
    pg.locator('[data-view=overlay]').click(); pg.wait_for_selector('.cmp-overlay canvas', timeout=15000); pg.wait_for_timeout(300)
    shot(pg, 'dev_cmp_overlay')
    ctx.close(); b.close()
print('\n'.join(console))
