from playwright.sync_api import sync_playwright
from pplus_common import *
from pypdf import PdfReader
import zipfile
ensure_server()
with sync_playwright() as p:
    b = launch(p)
    ctx = context(b); pg = ctx.new_page(); attach(pg, 'desk')
    pg.goto(URL); pg.wait_for_timeout(800)
    import_pdfs(pg, [os.path.join(TDP, 'raender.pdf'), os.path.join(TDP, 'bericht_v1.pdf'), os.path.join(TDP, 'bericht_v2.pdf')])
    rid = doc_id(pg, 'raender.pdf')
    goto(pg, f'#/werkzeug/zuschneiden?doc={rid}', '.cr-box')
    pg.locator('[data-auto]').click(); pg.wait_for_timeout(1200)
    shot(pg, 'dev_crop')
    pg.locator('.screen-foot .btn-primary').click()
    pg.wait_for_selector('[data-result] .result-card', timeout=20000)
    path = download_from(pg, pg.locator('[data-result] [data-r=dl]'), 'crop.pdf')
    r = PdfReader(path); print('crop', [list(map(float, x.cropbox)) for x in r.pages])
    bid = doc_id(pg, 'bericht_v1.pdf')
    goto(pg, f'#/werkzeug/lesezeichen?doc={bid}', '.bm-card')
    pg.locator('[data-gen]').click(); pg.wait_for_selector('.bm-row', timeout=15000); pg.wait_for_timeout(500)
    print(pg.evaluate("Array.from(document.querySelectorAll('.bm-row')).map(r => r.getAttribute('aria-level') + ' ' + r.querySelector('.bm-title').textContent + ' ' + r.querySelector('.bm-page').textContent)"))
    shot(pg, 'dev_bm')
    pg.locator('.screen-foot .btn-primary').click()
    pg.wait_for_selector('[data-result] .result-card', timeout=20000)
    path = download_from(pg, pg.locator('[data-result] [data-r=dl]'), 'bm.pdf')
    r = PdfReader(path)
    def walk(o, d=0):
        for x in o:
            if isinstance(x, list): walk(x, d + 1)
            else: print('  ' * d + x.title, r.get_destination_page_number(x) + 1)
    walk(r.outline)
    goto(pg, '#/werkzeug/stapel', '.bt-action')
    pg.locator('[data-lib]').click(); pg.wait_for_selector('dialog .pick-item')
    for i in range(pg.locator('dialog .pick-item input').count()): pg.locator('dialog .pick-item input').nth(i).check()
    pg.locator('dialog .btn-primary').click(); pg.wait_for_timeout(400)
    pg.locator('[data-action=numbers]').click()
    pg.locator('.screen-foot .btn-primary').click()
    pg.wait_for_selector('[data-result] .result-card', timeout=60000)
    shot(pg, 'dev_batch')
    path = download_from(pg, pg.locator('[data-result] [data-r=dl]'), 'batch.zip')
    print(zipfile.ZipFile(path).namelist())
    ctx.close(); b.close()
print('\n'.join(console))
