#!/usr/bin/env node
// Generates mail/cloud-init.yaml (from mail/server/* + mail/config/versions.json) and
// mail/config/MANIFEST.sha256 (hashes of the GitOps-applied files).
//   node mail/tools/build.mjs          → write both files
//   node mail/tools/build.mjs --check  → exit 1 if either file is stale or cloud-init exceeds 32 KiB
import { createHash } from 'node:crypto';
import { gzipSync } from 'node:zlib';
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const MAIL = join(dirname(fileURLToPath(import.meta.url)), '..');
const CHECK = process.argv.includes('--check');
const MAX_USER_DATA = 32 * 1024; // Hetzner Cloud user-data limit

const sha256 = (buf) => createHash('sha256').update(buf).digest('hex');
const walk = (dir) => readdirSync(dir).flatMap((n) => {
  const p = join(dir, n);
  return statSync(p).isDirectory() ? walk(p) : [p];
});

export function manifest() {
  const files = [
    ...walk(join(MAIL, 'config')).filter((p) => {
      const rel = relative(join(MAIL, 'config'), p);
      return rel !== 'MANIFEST.sha256' && !rel.startsWith('pairing/') && !rel.startsWith('sealed/');
    }),
    ...walk(join(MAIL, 'web')),
  ].map((p) => relative(MAIL, p).split('\\').join('/')).sort();
  return files.map((rel) => `${sha256(readFileSync(join(MAIL, rel)))}  ${rel}`).join('\n') + '\n';
}

export function cloudInit() {
  const v = JSON.parse(readFileSync(join(MAIL, 'config/versions.json'), 'utf8'));
  const pins = [
    `STALWART_VERSION=${v.stalwart.version}`,
    `STALWART_SHA256_X86_64=${v.stalwart.sha256.x86_64}`,
    `STALWART_SHA256_AARCH64=${v.stalwart.sha256.aarch64}`,
    `CLI_VERSION=${v.cli.version}`,
    `CLI_SHA256_X86_64=${v.cli.sha256.x86_64}`,
    `CLI_SHA256_AARCH64=${v.cli.sha256.aarch64}`,
    'MAIL_HOST=mail.fale.network',
    'MAIL_DOMAIN=fale.network',
    'FALE_SSH=off',
  ];
  const file = (path, src, mode) => {
    const raw = readFileSync(join(MAIL, src));
    return [
      `  - path: ${path}`,
      `    permissions: '${mode}'`,
      '    encoding: gz+b64',
      `    # source: mail/${src} (sha256 ${sha256(raw)})`,
      `    content: ${gzipSync(raw, { level: 9 }).toString('base64')}`,
    ].join('\n');
  };
  return [
    '#cloud-config',
    '# FaLe Mail server (mail.fale.network) – Ubuntu 24.04 LTS. Contains NO secrets: every password/key is generated',
    '# on the server. GENERATED by mail/tools/build.mjs from mail/server/* and mail/config/versions.json – do not edit.',
    '# Paste this whole file into the provider\'s "Cloud config" / "User data" field. Docs: docs/FALE-MAIL.md',
    'hostname: mail',
    'fqdn: mail.fale.network',
    'prefer_fqdn_over_hostname: true',
    'timezone: Europe/Berlin',
    'ssh_pwauth: false',
    'disable_root: true',
    'package_update: true',
    'package_upgrade: true',
    'packages: [unattended-upgrades, ufw, unbound, restic, git, python3-cryptography, openssl, ca-certificates, curl, xz-utils]',
    'write_files:',
    '  - path: /etc/fale-mail/pins.env',
    "    permissions: '0644'",
    '    content: |',
    ...pins.map((l) => `      ${l}`),
    file('/usr/local/lib/fale-mail/firstboot.sh', 'server/firstboot.sh', '0755'),
    file('/usr/local/lib/fale-mail/fale-mail-agent.py', 'server/fale-mail-agent.py', '0755'),
    'runcmd:',
    '  - [bash, /usr/local/lib/fale-mail/firstboot.sh]',
    'final_message: "FaLe Mail first boot finished after $UPTIME s – status: https://mail.fale.network/fale/status.json"',
    '',
  ].join('\n');
}

const outputs = [
  [join(MAIL, 'config/MANIFEST.sha256'), manifest()],
  [join(MAIL, 'cloud-init.yaml'), cloudInit()],
];
let stale = false;
for (const [path, content] of outputs) {
  const cur = existsSync(path) ? readFileSync(path, 'utf8') : '';
  // cloud-init gzip output is deterministic for identical input (no mtime in gzipSync), so a byte compare works.
  if (cur !== content) {
    stale = true;
    if (!CHECK) writeFileSync(path, content);
    console.log(`${CHECK ? 'STALE' : 'wrote'} ${relative(join(MAIL, '..'), path)}`);
  }
}
const size = Buffer.byteLength(outputs[1][1]);
console.log(`cloud-init.yaml: ${size} bytes (limit ${MAX_USER_DATA})`);
if (size > MAX_USER_DATA || (CHECK && stale)) process.exit(1);
